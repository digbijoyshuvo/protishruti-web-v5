const dicts: Record<Lang, Dict> = { en, bn };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string };
const I18nContext = createContext<Ctx>({ lang: "bn", setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === "undefined") return "bn";
    return (localStorage.getItem("lang") as Lang) || "bn";
  });

  useEffect(() => {
    if (typeof document !== "undefined") document.documentElement.lang = lang;
    if (typeof window !== "undefined") localStorage.setItem("lang", lang);
  }, [lang]);

  useEffect(() => {
    // Hydrate from profile when signed in
    (async () => {
      const { data } = await supabase.auth.getUser();
      if (!data.user) return;
      const { data: prof } = await supabase.from("profiles").select("language_pref").eq("id", data.user.id).maybeSingle();
      if (prof?.language_pref && prof.language_pref !== lang) setLangState(prof.language_pref as Lang);
    })();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    (async () => {
      const { data } = await supabase.auth.getUser();
      if (data.user) await supabase.from("profiles").update({ language_pref: l }).eq("id", data.user.id);
    })();
  };

  const t = (k: string) => dicts[lang][k] ?? dicts.en[k] ?? k;
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
